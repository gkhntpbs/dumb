// Run with PLAYWRIGHT_MODULE, CHROME_BIN, QA_ADMIN_PASSWORD_FILE and optional QA_ADMIN_URL.
import {readFileSync} from 'node:fs';
import {pathToFileURL,fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser=await chromium.launch({executablePath:process.env.CHROME_BIN,headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1100}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.QA_ADMIN_URL||'http://127.0.0.1:52147';
const password=process.env.QA_ADMIN_PASSWORD||readFileSync(process.env.QA_ADMIN_PASSWORD_FILE,'utf8').trim();
const evidence=fileURLToPath(new URL('../../docs/admin-evidence/',import.meta.url));
try{
await page.goto(base);
await page.locator('#login-status').filter({hasText:'Sign in to continue'}).waitFor();
await page.screenshot({path:evidence+'login.png',fullPage:true});
await page.locator('#password').fill('incorrect-runtime-attempt');
await page.locator('#login-submit').click();
await page.locator('#login-status').filter({hasText:'Incorrect password'}).waitFor();
assert.equal(await page.locator('#app').isVisible(),false);
await page.screenshot({path:evidence+'denied.png',fullPage:true});
await page.locator('#password').fill(password);await page.locator('#login-submit').click();
await page.locator('#status').filter({hasText:'Live'}).waitFor();
assert.equal(await page.locator('#password').inputValue(),'');
assert.equal((await context.cookies()).filter(c=>c.httpOnly&&c.sameSite==='Strict').length,1);
assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
await page.waitForFunction(()=>Chart.getChart(document.getElementById('activity-chart'))?.data.labels.length>=2);
assert.ok(await page.locator('#outcome-chart').evaluate(canvas=>!!Chart.getChart(canvas)));
await page.screenshot({path:evidence+'desktop.png',fullPage:true});
await page.reload();await page.locator('#status').filter({hasText:'Live'}).waitFor();
assert.equal(await page.locator('#access').isVisible(),false);
for(const [view,file] of [['workers','devices.png'],['queue','queue-retention.png'],['models','models.png'],['api','api.png']]){await page.locator(`[data-view="${view}"]`).click();await page.screenshot({path:evidence+file,fullPage:true});}
await page.locator('[data-view="api"]').click();
await page.locator('#api-status').filter({hasText:'Live API'}).waitFor();
assert.ok(await page.locator('#api-routes tr').count()>0);
assert.ok(await page.locator('#api-traffic-chart').evaluate(canvas=>Chart.getChart(canvas).data.datasets[0].data.some(n=>n>0)));
assert.equal(await page.locator('#model-filter').isVisible(),false);
assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).colorScheme),'dark');
await page.locator('[data-view="workers"]').click();await page.locator('#workers td button').first().click();
await page.locator('#details').waitFor();await page.screenshot({path:evidence+'worker-details.png',fullPage:true});
await page.locator('#details-close').click();
await page.locator('#workers-search').fill('no-such-worker');assert.equal(await page.locator('#workers tr').count(),0);await page.screenshot({path:evidence+'empty.png',fullPage:true});await page.locator('#workers-search').fill('');
await page.locator('[data-view="overview"]').click();
await page.setViewportSize({width:390,height:844});await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);await page.screenshot({path:evidence+'narrow.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
assert.equal(await page.locator('#logout').isVisible(),true);
await page.locator('[data-view="workers"]').click();await page.screenshot({path:evidence+'devices-mobile.png',fullPage:true});
await page.locator('[data-view="api"]').click();await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);await page.screenshot({path:evidence+'api-mobile.png',fullPage:true});
await page.locator('[data-view="models"]').click();await page.screenshot({path:evidence+'models-mobile.png',fullPage:true});
await page.locator('[data-view="queue"]').click();await page.screenshot({path:evidence+'queue-mobile.png',fullPage:true});
await page.locator('#queue td button').first().click();await page.screenshot({path:evidence+'job-details.png',fullPage:true});await page.locator('#details-close').click();
await page.locator('[data-view="overview"]').click();
await page.setViewportSize({width:1440,height:1100});
await page.route('**/admin/v1/summary?*',route=>route.fulfill({status:503,body:'unavailable'}));
await page.locator('#refresh').click();await page.locator('#status').filter({hasText:'Stale data'}).waitFor();
assert.ok(await page.locator('#metrics .metric').count()>0);await page.screenshot({path:evidence+'stale.png',fullPage:true});
await page.unroute('**/admin/v1/summary?*');
await page.locator('#refresh').click();await page.locator('#status').filter({hasText:'Live'}).waitFor();
await page.locator('[data-view="api"]').click();
await page.route('**/admin/v1/api',route=>route.fulfill({status:503,body:'unavailable'}));
await page.locator('#refresh').click();await page.locator('#api-status').filter({hasText:'Stale API data'}).waitFor();
await page.locator('#status').filter({hasText:'Live'}).waitFor();assert.ok(await page.locator('#api-routes tr').count()>0);await page.screenshot({path:evidence+'api-stale.png',fullPage:true});
await page.unroute('**/admin/v1/api');
await page.locator('#logout').click();await page.locator('#login-status').filter({hasText:'signed out'}).waitFor();
await page.reload();await page.locator('#login-status').filter({hasText:'Sign in to continue'}).waitFor();
assert.equal(await page.locator('#app').isVisible(),false);
assert.deepEqual(errors,[]);
console.log('Browser acceptance passed: negative/login/cookie/reload/views/details/search/mobile/stale/logout. No credentials stored or logged.');
}finally{await browser.close();}
